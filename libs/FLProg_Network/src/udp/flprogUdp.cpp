/*
 * FLProg_Network — flprogUdp.cpp
 * Назначение: Legacy FLProgUdpClient adapter поверх FLProgNetworkUdp/A3.
 *
 * Архитектурные заметки:
 * - Сохраняет старые begin/beginPacket/endPacket/read/write и change-flags.
 * - DNS WAIT/BUSY/SUCCESS/ERROR переводятся в legacy control-status/result codes.
 * - Это Gate 0.3: сначала compile/API, затем отдельный semantic UDP echo test.
 *
 * Комментарии описывают контракт и причины решений; рабочую логику файла не дублируют.
 * Расширенный контракт сопровождения:
 * - Legacy UDP/DNS API остается фасадом над native route-aware реализацией и не дублирует socket state.
 * - Повторные вызовы должны сохранять неблокирующую семантику SUCCESS/WAIT/ERROR, ожидаемую FLProg.
 * - Кэш, TTL и packet boundaries переводятся в compatibility слое, а не в hardware backend.
 * Extended maintenance contract:
 * - The legacy UDP/DNS API remains a facade over the native route-aware implementation and does not duplicate socket state.
 * - Repeated calls keep the non-blocking SUCCESS/WAIT/ERROR semantics expected by FLProg.
 * - Cache, TTL and packet boundaries are translated in the compatibility layer, not in the hardware backend.
 */
#include "flprogUdp.h"

// Legacy setSourse() changes only the owning NetworkDevice reference.
// If UDP was already opened, close the native socket first so a lease from
// the previous device cannot survive behind the compatibility facade.
void FLProgUdpClient::setSourse(FLProgAbstractTcpInterface *sourse)
{
    if (_sourse == sourse)
    {
        return;
    }

    if (_nativeBegun)
    {
        FLProgNetworkUdp::stop();
        _nativeBegun = false;
    }

    _sourse = sourse;
    _port = 0;
    _compatError = FLPROG_NOT_ERROR;
    _compatStatus =
        (_sourse == nullptr)
            ? FLPROG_NOT_REDY_STATUS
            : FLPROG_READY_STATUS;

    applyDnsCachePolicy();

    _oldCompatStatus = _compatStatus;
    _oldCompatError = _compatError;
    _isChangeStatus = false;
    _isChangeError = false;
}

// Bind a local UDP port through the native A3 route.
// Return values are deliberately translated to the old FLPROG_* contract;
// callers generated by older FLProg versions depend on these numeric values.
uint8_t FLProgUdpClient::begin(uint16_t port)
{
    if (_sourse == nullptr || !_sourse->isInit())
    {
        _compatStatus = FLPROG_NOT_REDY_STATUS;
        _compatError = FLPROG_ETHERNET_INTERFACE_NOT_READY_ERROR;
        setFlags();
        return FLPROG_ERROR;
    }

    if (_nativeBegun && _port == port)
    {
        _compatStatus = FLPROG_READY_STATUS;
        _compatError = FLPROG_NOT_ERROR;
        setFlags();
        return FLPROG_SUCCESS;
    }

    if (_nativeBegun)
    {
        FLProgNetworkUdp::stop();
        _nativeBegun = false;
    }

    if (!FLProgNetworkUdp::begin(
            *_sourse,
            FLPROG_NETWORK_ROUTE_DEFAULT,
            port))
    {
        _compatStatus = FLPROG_READY_STATUS;
        _compatError = FLPROG_ETHERNET_SOKET_INDEX_ERROR;
        setFlags();
        return FLPROG_ERROR;
    }

    _nativeBegun = true;
    _port = port;
    _compatStatus = FLPROG_READY_STATUS;
    _compatError = FLPROG_NOT_ERROR;
    setFlags();
    return FLPROG_SUCCESS;
}

// Multicast uses the same native UDP object; the adapter only preserves the
// old method name/result convention. No legacy MACRAW/socket table is restored.
uint8_t FLProgUdpClient::beginMulticast(IPAddress ip, uint16_t port)
{
    if (_sourse == nullptr || !_sourse->isInit())
    {
        _compatStatus = FLPROG_NOT_REDY_STATUS;
        _compatError = FLPROG_ETHERNET_INTERFACE_NOT_READY_ERROR;
        setFlags();
        return 0;
    }

    if (_nativeBegun)
    {
        FLProgNetworkUdp::stop();
        _nativeBegun = false;
    }

    if (!FLProgNetworkUdp::beginMulticast(
            *_sourse,
            FLPROG_NETWORK_ROUTE_DEFAULT,
            ip,
            port))
    {
        _compatStatus = FLPROG_READY_STATUS;
        _compatError = FLPROG_ETHERNET_UDP_SOKET_START_ERROR;
        setFlags();
        return 0;
    }

    _nativeBegun = true;
    _port = port;
    _compatStatus = FLPROG_READY_STATUS;
    _compatError = FLPROG_NOT_ERROR;
    setFlags();
    return 1;
}

// Start an outgoing packet to a resolved IP. begin() must have succeeded
// first, matching the lifecycle expected by the old FLProg UDP blocks.
int FLProgUdpClient::beginIpPacket(IPAddress ip, uint16_t port)
{
    if (!_nativeBegun || _sourse == nullptr)
    {
        _compatError = FLPROG_ETHERNET_UDP_SOKET_START_ERROR;
        setFlags();
        return FLPROG_ERROR;
    }

    if (FLProgNetworkUdp::beginPacket(ip, port) != 0)
    {
        _compatStatus = FLPROG_READY_STATUS;
        _compatError = FLPROG_NOT_ERROR;
        setFlags();
        return FLPROG_SUCCESS;
    }

    _compatError = FLPROG_ETHERNET_UDP_SOKET_START_ERROR;
    setFlags();
    return FLPROG_ERROR;
}

// Host-name path stays non-blocking: DNS may return WAIT/BUSY and the old
// caller receives FLPROG_WAIT instead of a native DNS enum value.
int FLProgUdpClient::beginPacket(const char *host, uint16_t port)
{
    if (_sourse == nullptr || host == nullptr || host[0] == 0)
    {
        _compatStatus = FLPROG_READY_STATUS;
        _compatError = FLPROG_ETHERNET_DNS_INVALID_RESPONSE;
        setFlags();
        return FLPROG_ERROR;
    }

    FLProgNetworkDns *resolver = _sourse->dnsResolver();
    if (resolver == nullptr)
    {
        _compatStatus = FLPROG_READY_STATUS;
        _compatError = FLPROG_ETHERNET_DNS_INVALID_RESPONSE;
        setFlags();
        return FLPROG_ERROR;
    }

    applyDnsCachePolicy();

    const uint8_t result =
        resolver->resolve(host, FLPROG_NETWORK_ROUTE_DEFAULT);

    if (
        result == FLPROG_DNS_RESULT_WAIT ||
        result == FLPROG_DNS_RESULT_BUSY)
    {
        _compatStatus = FLPROG_WAIT_ETHERNET_DNS_STATUS;
        _compatError = FLPROG_NOT_ERROR;
        setFlags();
        return FLPROG_WAIT;
    }

    if (result != FLPROG_DNS_RESULT_SUCCESS)
    {
        _compatStatus = FLPROG_READY_STATUS;
        _compatError = FLPROG_ETHERNET_DNS_INVALID_RESPONSE;
        setFlags();
        return FLPROG_ERROR;
    }

    _compatStatus = FLPROG_READY_STATUS;
    return beginIpPacket(resolver->result(), port);
}

// Commit the packet in the native UDP backend, then convert success/error
// to legacy result codes. Native and legacy numeric enums are not identical.
int FLProgUdpClient::endPacket()
{
    const int result = FLProgNetworkUdp::endPacket();

    if (result != 0)
    {
        _compatError = FLPROG_NOT_ERROR;
        setFlags();
        return FLPROG_SUCCESS;
    }

    _compatError = FLPROG_ETHERNET_UDP_SOKET_START_ERROR;
    setFlags();
    return FLPROG_ERROR;
}

int FLProgUdpClient::parsePacket()
{
    return FLProgNetworkUdp::parsePacket();
}

// stop() releases the A3 UDP lease and resets only this compatibility object.
// It must not reset the NetworkDevice or neighbouring sockets.
void FLProgUdpClient::stop()
{
    FLProgNetworkUdp::stop();
    _nativeBegun = false;
    _port = 0;
    _compatStatus = FLPROG_NOT_REDY_STATUS;
    _compatError = FLPROG_NOT_ERROR;
    setFlags();
}

void FLProgUdpClient::setDnsCacheStorageTime(uint32_t time)
{
    _legacyDnsCacheStorageTime = time;
    applyDnsCachePolicy();
}

// Convert only at the compatibility boundary: old API expresses cache time
// in milliseconds, while native DNS stores the TTL in seconds.
void FLProgUdpClient::applyDnsCachePolicy()
{
    if (_sourse == nullptr)
    {
        return;
    }

    FLProgNetworkDns *resolver = _sourse->dnsResolver();
    if (resolver == nullptr)
    {
        return;
    }

    // Legacy API is milliseconds. Native DNS stores TTL in seconds.
    const uint32_t seconds =
        (_legacyDnsCacheStorageTime == 0)
            ? 0
            : ((_legacyDnsCacheStorageTime + 999UL) / 1000UL);

    resolver->setMaxCacheTtl(seconds);
}

// Legacy change flags are edge-latches: once a status/error changes they stay
// set until the corresponding *WithReset() getter clears them.
void FLProgUdpClient::setFlags()
{
    if (_compatStatus != _oldCompatStatus)
    {
        _oldCompatStatus = _compatStatus;
        _isChangeStatus = true;
    }

    if (_compatError != _oldCompatError)
    {
        _oldCompatError = _compatError;
        _isChangeError = true;
    }
}
