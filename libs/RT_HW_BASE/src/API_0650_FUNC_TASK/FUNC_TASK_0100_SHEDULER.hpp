//										1.Диспетчер задач 					   1	 2	   4	 8      16     32  	 6 4    128
//  uint8_t  shead.event=0;		//--Флаги событий  по времени: bit.x: loop(), 10ms,  25ms, 50ms, 100ms, 250ms, 500ms, 1000ms; 
//  uint8_t  shead.meander=0;	//--Флаги меандров по времени: bit.x: loop(), 10ms,  25ms, 50ms, 100ms, 250ms, 500ms, 1000ms; 
//  uint8_t  shead.run=0; 		//--Флаги запуска задач:       bit.x: frdm,   quick, fast, t50,  back,  slow,  t500,  t1000; 
