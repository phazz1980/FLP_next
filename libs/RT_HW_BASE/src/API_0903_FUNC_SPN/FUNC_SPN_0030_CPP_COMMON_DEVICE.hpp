//									4.10. Запись байта tx, возвращает прочитанный байт;
//=================================================================================================
  uint8_t	RT_HW_BASE::	spnTransferVar(RT_HW_STRUCT_SPN_DEV &id, uint8_t tx){				 
	uint8_t rx=0; (void)rx; (void)id; (void)tx;
	if((!id.permitMISO) || (!id.permitMOSI)){id.codeErr=201; id.link=1; return 1;} //--Недопустимые параметры;
//-------------------------------------------------------------------------------------------------
	id.link=0;													//--Сброс флага успешного завершения;
	digitalWrite(id.sck,0);										//  0--->SCK;	
//- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
	digitalWrite(id.cs,0);										//  0--->CS; 								
//-------------------------------------------------------------------------------------------------
		for(int8_t i=7; i>=0; i--){								//--Побитовые операции;							
			digitalWrite(id.mosi,(tx & (1<<i)));				//--Побитовый вывод;	
			digitalWrite(id.sck,1); 							//  1--->SCK;
			RT_HW_DELAY(id.time);								//--Задержка;                            
			if(digitalRead(id.miso)){rx |=(1<<i);} 				//--Побитовый ввод; 
			digitalWrite(id.sck,0); 							//  0--->SCK;
			RT_HW_DELAY(id.time);								//--Задержка;   			
		}														//--END for();																					
//-------------------------------------------------------------------------------------------------
	digitalWrite(id.cs,1);										//  1--->CS; 
//- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
	digitalWrite(id.sck, 0);									//  0--->SCK;  
	digitalWrite(id.mosi,0);									//  0--->MOSI;
	id.link=1;													//--Установка флага успешного завершения;
	return rx;													//--Возвращает прочитанный байт;
  };
