//=================================================================================================
//									4.5. spnInitDevice(id)
//=================================================================================================
  void		RT_HW_BASE::	spnInitDevice(RT_HW_STRUCT_SPN_DEV &id){ 
	id.link=1;
	if(id.custom==0){id.codeErr=50; return;} 
	if(id.status==1){id.codeErr=0;  return;}
	id.status=id.codeErr=0;
//-------------------------------------------------------------------------------------------------
	if(!checkPinDOT(id.sck)) {id.codeErr=150; return;}	//--Ошибка пина SCK;
	if(!checkPinDOT(id.cs))  {id.codeErr=151; return;}	//--Ошибка пина SCK;
//-------------------------------------------------------------------------------------------------
					                           digitalWrite(id.sck, 0); pinMode(id.sck, OUTPUT);
					                           digitalWrite(id.cs,  1); pinMode(id.cs,  OUTPUT);
//-------------------------------------------------------------------------------------------------
	if( checkPinDIN(id.miso)){id.permitMISO=1;                          pinMode(id.miso,INPUT_PULLUP);}	//--Разрешение MISO, если допустимый пин;	
	if( checkPinDOT(id.mosi)){id.permitMOSI=1; digitalWrite(id.mosi,0); pinMode(id.mosi,OUTPUT); }		//--Разрешение MOSI, если допустимый пин;			
	if( checkPinDOT(id.oe))  {id.permitOE  =1; digitalWrite(id.oe,  1); pinMode(id.oe,  OUTPUT);}		//--Разрешение   OE, если недопустимый пин;			
//-------------------------------------------------------------------------------------------------
	if(id.speed>100){id.speed=100;} id.time=10-(id.speed/10);	
//-------------------------------------------------------------------------------------------------
	id.custom=id.status=id.link=1;	
  };
