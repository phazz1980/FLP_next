//=================================================================================================
  void   	RT_HW_BASE:: 	i2cBeginTransmission(uint8_t adr, uint8_t bus){
	(void)adr; (void)bus;
//-------------------------------------------------------------------------------------------------
		if(i2cGetStatus(bus)!=1){						return;};	//--Выход если шина не Master;
//-------------------------------------------------------------------------------------------------	
	#if defined(RT_HW_PRESENT_I2C0)
		if(bus==0){Wire.beginTransmission(adr); 		return;};
	#endif					
//-------------------------------------------------------------------------------------------------		
  };
//=================================================================================================
//									2.2. Завершение транзакции обмена i2cx
//=================================================================================================
  uint8_t 	 RT_HW_BASE:: 	i2cEndTransmission(uint8_t bus){
	(void)bus;
//-------------------------------------------------------------------------------------------------
		if(i2cGetStatus(bus)!=1){						return 5;};	//--Выход если шина не Master;
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PRESENT_I2C0)
		if(bus==0){return Wire.endTransmission();};
	#endif			
//-------------------------------------------------------------------------------------------------	
		return 6;
//-------------------------------------------------------------------------------------------------
  };
