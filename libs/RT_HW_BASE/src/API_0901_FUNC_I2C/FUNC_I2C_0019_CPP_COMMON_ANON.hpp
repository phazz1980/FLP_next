  uint8_t  	RT_HW_BASE:: 	i2cBegin(			  uint8_t bus){
	(void)bus;
//-------------------------------------------------------------------------------------------------
	i2cClearCodeErr(bus);										//--Сброс кода ошибки;
	if(!i2cCheckBus(bus))	 {i2cSetCodeErr(65,bus); return 1;}	//--Выход, если недопустимый номер шины;
	if( i2cGetStatus(bus)==1){            			 return 1;} //--Выход, если шина уже Master;
	if(!i2cSetBusy(bus))	 {            			 return 0;}	//--Захват шины или выход еcли шина занята;
    i2cEnd(bus);												//--Отключение шины i2c (если вдруг раньше была инициализирована функцией Wirex.begin();
//-------------------------------------------------------------------------------------------------
//						Проверка подтяжки(Vcc) пинов SDA,SCL (обычно внешние резисторы 10к)
//-------------------------------------------------------------------------------------------------
	uint8_t pin;
	pin=i2cGetPinSDA(bus); if(pin==255) {return 1;} pinMode(pin,INPUT_PULLUP); if(!digitalRead(pin)){i2cSetCodeErr(61,bus); return 1;} 
	pin=i2cGetPinSCL(bus); if(pin==255) {return 1;} pinMode(pin,INPUT_PULLUP); if(!digitalRead(pin)){i2cSetCodeErr(61,bus); return 1;}  
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PRESENT_I2C0)	
		if(bus==0){		
			Wire.begin();										//--Инициализация шины как Master;
			Wire.setClock(i2cGetSpeed(bus));					//--Установка скорости;	
			i2cSetStatus(1,bus);								//--Установка регистра status=1(Master);
			i2cClearBusy(bus); 									//--Сброс регистра занятости шины;
		return 1;												//--Успешный выход;
		}
	#endif													//--Выход по ошибке;
//-------------------------------------------------------------------------------------------------
		return 0;
//-------------------------------------------------------------------------------------------------  
  };	//====END	uint8_t  RT_HW_BASE:: i2cBegin(uint8_t bus)
