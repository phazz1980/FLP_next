  uint8_t  	RT_HW_BASE:: 	i2cBegin(			  uint8_t bus){
	(void)bus;
//-------------------------------------------------------------------------------------------------
	i2cClearCodeErr(bus);										//--Сброс кода ошибки;
	if(!i2cCheckBus(bus))	 {i2cSetCodeErr(65,bus); return 1;}	//--Выход, если недопустимый номер шины;
	if( i2cGetStatus(bus)==1){            			 return 1;} //--Выход, если шина уже Master;
	if(!i2cSetBusy(bus))	 {            			 return 0;}	//--Захват шины или выход еcли шина занята;
    i2cEnd(bus);												//--Отключение шины i2c (если вдруг раньше была инициализирована функцией Wirex.begin();
//-------------------------------------------------------------------------------------------------
//						Проверка подтяжки(Vcc) пинов SDA,SCL (обычно внешние резисторы 10к)
//-------------------------------------------------------------------------------------------------
	uint8_t pin;
//	pin=i2cGetPinSDA(bus); if(pin==255) {return 1;} pinMode(pin,INPUT); if(!digitalRead(pin)){i2cSetCodeErr(61,bus); return 1;} 
	pin=i2cGetPinSCL(bus); if(pin==255) {return 1;} pinMode(pin,INPUT); if(!digitalRead(pin)){i2cSetCodeErr(62,bus); return 1;}    
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PRESENT_I2C0)	
		if(bus==0){
			Wire.setSDA(i2cGetPinSDA(bus));						//--Установка пина SDA;		
			Wire.setSCL(i2cGetPinSCL(bus));						//--Установка пина SCL;		
			Wire.begin();										//--Инициализация шины как Master;
			Wire.setClock(i2cGetSpeed(bus));;					//--Установка скорости;	
			i2cSetStatus(1,bus);								//--Установка регистра status=1(Master);
			i2cClearBusy(bus); 									//--Сброс регистра занятости шины;
		return 1;												//--Успешный выход;
		}
	#endif
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PRESENT_I2C1)	
		if(bus==1){
			Wire1.setSDA(i2cGetPinSDA(bus));					//--Установка пина SDA;		
			Wire1.setSCL(i2cGetPinSCL(bus));					//--Установка пина SCL;		
			Wire1.begin();										//--Инициализация шины как Master;
			Wire1.setClock(i2cGetSpeed(bus));;					//--Установка скорости;	
			i2cSetStatus(1,bus);								//--Установка регистра status=1(Master);
			i2cClearBusy(bus); 									//--Сброс регистра занятости шины;
		return 1;												//--Успешный выход;
		}
	#endif
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PRESENT_I2C2)	
		if(bus==2){
			Wire2.setSDA(i2cGetPinSDA(bus));					//--Установка пина SDA;		
			Wire2.setSCL(i2cGetPinSCL(bus));					//--Установка пина SCL;		
			Wire2.begin();										//--Инициализация шины как Master;
			Wire2.setClock(i2cGetSpeed(bus));;					//--Установка скорости;	
			i2cSetStatus(1,bus);								//--Установка регистра status=1(Master);
			i2cClearBusy(bus); 									//--Сброс регистра занятости шины;
		return 1;												//--Успешный выход;
		}
	#endif	
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PRESENT_I2C3)	
		if(bus==3){
			Wire3.setSDA(i2cGetPinSDA(bus));					//--Установка пина SDA;		
			Wire3.setSCL(i2cGetPinSCL(bus));					//--Установка пина SCL;		
			Wire3.begin();										//--Инициализация шины как Master;
			Wire3.setClock(i2cGetSpeed(bus));;					//--Установка скорости;	
			i2cSetStatus(1,bus);								//--Установка регистра status=1(Master);
			i2cClearBusy(bus); 									//--Сброс регистра занятости шины;
		return 1;												//--Успешный выход;
		}
	#endif
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PRESENT_I2C100)	
		if(bus==100){
			Wire100.setTxBuffer(RT_HW_I2C100_TxBuffer, sizeof(RT_HW_I2C100_TxBuffer));
			Wire100.setRxBuffer(RT_HW_I2C100_RxBuffer, sizeof(RT_HW_I2C100_RxBuffer));
			Wire100.setDelay_us(0);
			Wire100.setTimeout(1000);
			Wire100.setSda(i2cGetPinSDA(bus));					//--Установка пина SDA;		
			Wire100.setScl(i2cGetPinSCL(bus));					//--Установка пина SCL;		
			Wire100.begin();									//--Инициализация шины как Master;
			Wire100.setClock(i2cGetSpeed(bus));;				//--Установка скорости;	
			i2cSetStatus(1,bus);								//--Установка регистра status=1(Master);
			i2cClearBusy(bus); 									//--Сброс регистра занятости шины;
		return 1;												//--Успешный выход;
		}
	#endif	
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PRESENT_I2C101)	
		if(bus==101){
			Wire101.setSda(i2cGetPinSDA(bus));					//--Установка пина SDA;		
			Wire101.setScl(i2cGetPinSCL(bus));					//--Установка пина SCL;		
			Wire101.begin();									//--Инициализация шины как Master;
			Wire101.setClock(i2cGetSpeed(bus));;				//--Установка скорости;	
			i2cSetStatus(1,bus);								//--Установка регистра status=1(Master);
			i2cClearBusy(bus); 									//--Сброс регистра занятости шины;
		return 1;												//--Успешный выход;
		}
	#endif	
//-------------------------------------------------------------------------------------------------
		i2cSetCodeErr(70,bus);									//--Установка кода ошибки "No bus";
		i2cClearBusy(bus); 										//--Сброс регистра занятости шины;;
		return 1;												//--Выход по ошибке;
//-------------------------------------------------------------------------------------------------
  };	//====END	uint8_t  RT_HW_BASE:: i2cBegin(uint8_t bus)
