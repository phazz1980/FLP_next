//=================================================================================================
  uint8_t     RT_HW_BASE:: 	i2cSetParam(RT_HW_STRUCT_I2C_DEV &id){
	if(id.custom==0){
		id.link=id.status=id.codeErr=0; 
		id.custom=1;
	}
	return id.custom;		
  };
//=================================================================================================
// 		    						1.1.2. Установка параметров
//=================================================================================================
  uint8_t	RT_HW_BASE::	i2cSetParam  (RT_HW_STRUCT_I2C_DEV &id, uint8_t addr, uint8_t bus, uint32_t speed){
	(void)addr; (void)bus; (void)speed;
		if(id.custom==0){
			id.link=id.status=id.codeErr=id.err=0; 
			id.addr=addr; 
			id.bus=bus; 
			id.speed=speed; id.custom=1;
		}
	return id.custom;	
  }; 
//=================================================================================================
// 		    						1.1.3. Установка параметров
//=================================================================================================  
   uint8_t	RT_HW_BASE::	i2cSetParam	(RT_HW_STRUCT_I2C_DEV &id, uint8_t addr, uint8_t bus,   uint32_t speed, uint8_t expander, uint8_t channel){
		id.expander=expander; 
		id.channel=channel;	
		return i2cSetParam(id,addr,bus,speed);
   };									
//=================================================================================================
// 		    						1.2. Инициализация устройства как Master
//=================================================================================================
  void		RT_HW_BASE::	i2cInitDevice(RT_HW_STRUCT_I2C_DEV &id){
	id.link=0;
	if(id.custom==0){id.codeErr=50; id.link=1; return;} //--Выход по ошибке =50, если параметры устройство не настроено;
	if(id.status==1){id.codeErr=0;  id.link=1; return;}	//--Успешный выход,	если шина настроена как Master;
	if(id.err==1)   {id.codeErr=51; id.link=1; return;}
	id.status=id.codeErr=0;
//------------------------------------------------------------------------------------------------
	if(!i2cCheckBus(id.bus))	{id.codeErr=52; id.err=1; id.link=1; 	return;}	//--Проверка допустимости номера шины i2c;
    if(!i2cBegin(id.bus))		{				             			return;}	//--Инициализация 	   шины i2c как Master;								  
	if( i2cGetStatus(id.bus)!=1){id.codeErr=53; id.err=1; id.link=1; 	return;}	//--Проверка настройки шины i2c как Master;
//-------------------------------------------------------------------------------------------------
	if(id.speed==0){id.speed=RT_HW_I2C_SPEED;}			//--Установка значения скорости шины по умолчанию;
	id.status=i2cGetStatus(id.bus); 					//--Установка состояния настройки устройства =Master;		
	id.link=1;											//--Установка флага link (успешное завершение);
  };	
//=================================================================================================
// 		    						1.3. Утилита: начальные действия функции обмена 
//									   с устройствами i2c (RT_HW_STRUCT_I2C_DEV &id)
//=================================================================================================
  uint8_t	RT_HW_BASE::	i2cBeginFunc (RT_HW_STRUCT_I2C_DEV &id){
	id.link=0;											//--Очистка флага link(флаг успешного завершения обмена);
	if(i2cGetStatus(id.bus)!=1) {id.link=1; return 1;}	//--Выход если шина i2c не настроена как Master;
	if(i2cSetBusy  (id.bus)==0) {           return 1;}	//--Захват шины i2c;
	i2cSetClock(id.speed,id.bus);						//--Установка скорости шины для обмена с утройством;
	i2cSetChannel(id);									//--При подключении устройства через расширитель i2c, настройка расширителя;
	return 0;												//--Выход успешный;										
  } ;
//=================================================================================================
// 		    						1.4. Утилита: завершающие действия функции обмена 
//									   с устройствами i2c (RT_HW_STRUCT_I2C_DEV &id)
//=================================================================================================
  void		RT_HW_BASE::	i2cEndFunc   (RT_HW_STRUCT_I2C_DEV &id){
	i2cClearChannel(id);								//--Сброс расширителя i2c;	
	i2cSetClock(i2cGetSpeed(id.bus),id.bus);			//--Установка значения скорости шины по умолчанию;
	i2cClearBusy(id.bus); 								//--Освобождение шины i2c;	
	id.link=1;											//--Установка флага link (успешное завершение);
  };
//=================================================================================================
// 		    						1.5. Поиск устройства на шине i2c 
//=================================================================================================
  void		RT_HW_BASE::	i2cFindAddr (RT_HW_STRUCT_I2C_DEV &id){ 
	if(i2cBeginFunc(id)){return;}					//--Проверка готовности, настройка и захват шины, настройка расширителя i2c;
//-------------------------------------------------------------------------------------------------
	i2cBeginTransmission(id); 						//--Начальная   транзакция для обмена с устройством;
	i2cEndTransmission(id);							//--Завершающая транзакция для обмена с устройством;
//-------------------------------------------------------------------------------------------------
	i2cEndFunc(id);									//--Освобождение шины i2c, сброс расширителя i2c;
  };

  
//================================================================================================
// 		    						1.6. Поиск устройства на шине i2c 
//  При ошибке поиска адреса выполняется 6-ть повторов:                                                                                                                                                                                                                                                                                                 
//		первые    три повтора с периодом(ms) 100+(periodFind*id.cntErr);
//		следующие три повтора с периодом(ms) 2000ms;
//		на выходе id.ok>1 (id.ok=id.codeErr);
//	Успешный поиск выполняется qntFind раз c периодом periodFind - на выходе id.ok=1;
//		В процессе поиска адреса id.ok=1.
//=================================================================================================
 void RT_HW_BASE:: i2cFindAddr (RT_HW_STRUCT_I2C_DEV &id, uint8_t qnt, uint8_t period){ 
	if(id.step==0)  {id.ok=id.cnt=0; id.err=id.cntErr=id.codeErr=0; 	id.step=10;}	//--Инициализация параметров;
//-------------------------------------------------------------------------------------------------	
	if(id.step==200){if(!getIsTimerMs(id.timeBegin,id.period)){return;} id.step=10;}	//--Программная задержка;
	//---------------------------------------------------------------------------------------------
	if(id.step==10){
		//--------------------------- Транзакция с адресом устройства -----------------------------
		if(!id.link)		{return;}			//--Выход, если линия	не готова;	
		if(i2cBeginFunc(id)){return;}			//--Проверка готовности, настройка и захват шины, настройка расширителя i2c;
		i2cBeginTransmission(id); 				//--Начальная   транзакция для обмена с устройством;
		i2cEndTransmission(id);					//--Завершающая транзакция для обмена с устройством;
		i2cEndFunc(id);							//--Освобождение шины i2c, сброс расширителя i2c;					
		id.step=200;	id.timeBegin=millis();	//--Подготовка параметров для программной задержки; 		
		//--------------------------- Обработка при ошибке транзакции -----------------------------
		if(id.codeErr){
			id.ok=0; id.cnt=0;  	 
			if(id.cntErr>=3){id.err=1; id.codeErr=21; id.period=2000;	return;}
			id.period=50+(200*id.cntErr++); 							return;	
		}
		//---------------------------- Обработка при успешной транзакции --------------------------
			id.err=0; id.cntErr=0; id.codeErr=0; 
			if(++id.cnt>=qnt)	{id.ok=1; id.step=0;    return;}	//--Успешное завершение;
			id.period=period;	
			return;		//--Переход на повторение доступности адреса:
	}
//-------------------------------------------------------------------------------------------------				
}; 
