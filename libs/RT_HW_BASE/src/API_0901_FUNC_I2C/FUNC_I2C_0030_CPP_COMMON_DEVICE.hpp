//=================================================================================================
// 		    		3.1. Утилита: Запрос и чтение в буфер i2c qnt байт c тайм-аутом
//=================================================================================================
  void		RT_HW_BASE:: 	i2cRequestFromFunc(RT_HW_STRUCT_I2C_DEV &id, uint16_t qnt){
	uint8_t cnt=i2cRequestFrom(qnt, id.addr, id.bus, id.stop);//--Запрос qnt bytes;
	if(cnt!=qnt){id.codeErr=5; return;}					//--Ошибка =5, если кол-во возвращаемых байт не равно кол-ву запрошенных байт;
	uint32_t timeBegin=micros();
	uint32_t timeEnd;
	uint16_t time=100*qnt;
	do{													//--Ожидание (в цикле с тайм аутом) прихода в буфер i2c qnt запрощенных байт;
		cnt=i2cAvailable(id.bus);						//--Ожидание (в цикле с тайм аутом) прихода в буфер i2c qnt запрощенных байт;
		timeEnd=micros();								//--Фиксация текущего времени для контроля тайм-аута;
		if(cnt>=qnt){break;}							//--Проверка заполнения буфера чтения qnt байтами;
		if(timeEnd>=timeBegin){if((timeEnd   - timeBegin)>time) {id.codeErr=6; return;}}
		else                  {if((timeBegin - timeEnd)  >time) {id.codeErr=6; return;}}
    }
	while(1);    										//--Ожидание завершения цикла do{};				  
														//--Выход успешный;	
};
//=================================================================================================
// 		    						3.2. Чтение байта в id.bf8
//=================================================================================================
  void  	RT_HW_BASE::	i2cRead(RT_HW_STRUCT_I2C_DEV &id){ 
	if(i2cBeginFunc(id)){return;}					//--Проверка готовности, настройка и захват шины, настройка расширителя i2c;
	i2cRequestFromFunc(id, 1);						//--Запрос и прием в буфер qnt байтов;
	if(id.codeErr==0){id.bf8=i2cRead(id.bus);}		//--Чтение qnt байт в массив arr из буфера i2c;	
	i2cEndFunc(id);									//--Освобождение шины i2c, сброс расширителя i2c;
  };
//=================================================================================================
// 		    						3.3. Чтение qnt байт в массив arr
//=================================================================================================
  void   	RT_HW_BASE::	i2cReadArr(RT_HW_STRUCT_I2C_DEV &id, uint8_t *arr, uint16_t qnt){ 
	if(qnt>32) {qnt=32;};							//--Нормализация параметра qnt;
	if(i2cBeginFunc(id)){return;}					//--Проверка готовности, настройка и захват шины, настройка расширителя i2c;
	i2cRequestFromFunc(id, qnt);					//--Запрос и прием в буфер qnt байтов;
	if(id.codeErr==0){								//--Чтение 
		for(uint8_t i=0; i<qnt; i++){				//     qnt байт				
			arr[i]=i2cRead(id.bus);					// 			в массив arr из буфера i2c;	
		}
	}	
	i2cEndFunc(id);									//--Освобождение шины i2c, сброс расширителя i2c;
  };
//=================================================================================================
// 		    						3.4. Чтение из регистра reg байта в id.bf8
//=================================================================================================
  void  	RT_HW_BASE::	i2cReadRegVar(RT_HW_STRUCT_I2C_DEV &id, uint8_t reg){
	if(i2cBeginFunc(id)){return;}						//--Проверка готовности, настройка и захват шины, настройка расширителя i2c;
	i2cBeginTransmission(id); 						//--Начальная   транзакция для обмена с устройством;	
	i2cWrite(reg,id.bus); 							//--Отправка регистра;
	i2cEndTransmission(id);							//--Завершающая транзакция для обмена с устройством;
//------------------------------------------------------------------------------------------------  
	if(id.codeErr==0){i2cRequestFromFunc(id,1);}	//--Запрос и прием в буфер qnt байтов;
	if(id.codeErr==0){id.bf8=i2cRead(id.bus);}		//--Чтение qnt байт в массив arr из буфера i2c;	
//------------------------------------------------------------------------------------------------
	i2cEndFunc(id);									//--Освобождение шины i2c, сброс расширителя i2c;		
  };
