// 		    						2.3. Подключение устройства через расширитель шины i2c(TCA9584A)
//										(если устройство подключено через расширитель)
//=================================================================================================
  void  	RT_HW_BASE::	i2cSetChannel(RT_HW_STRUCT_I2C_DEV &id){
	if(id.expander){									//--Проверка на наличие расширителя;
		if((id.channel>0) && (id.channel<=8)){			//--Проверка на допустимость номера канала;
			uint8_t bf=0; 								//--Создание временной переменной;
			bitSet(bf,(id.channel-1));					//--Установка в переменной бита соответствующего номера канала;
			i2cBeginTransmission(id.expander,id.bus);	//--Начальная   транзакция для обмена с расширителем;
			i2cWrite(bf,id.bus);						//--Запись регистра управления каналами;
			i2cEndTransmission(id.bus);					//--Завершающая транзакция для обмена с расширителем;
			//delayMicroseconds(10);
		}
	}
  };
//=================================================================================================
// 		    						2.4. Отключение устройства через расширитель шины i2c(TCA9584A)
//										(если устройство подключено через расширитель)
//=================================================================================================
  void  	RT_HW_BASE::	i2cClearChannel(RT_HW_STRUCT_I2C_DEV &id){
	if(id.expander){								//--Проверка на наличие расширителя;
        i2cBeginTransmission(id.expander,id.bus);	//--Начальная   транзакция для обмена с расширителем;
        i2cWrite((uint8_t)0,id.bus);							//--Очистка регистра управления каналами;
        i2cEndTransmission(id.bus);					//--Завершающая транзакция для обмена с расширителем;
		//delayMicroseconds(10);	
	}
  };
