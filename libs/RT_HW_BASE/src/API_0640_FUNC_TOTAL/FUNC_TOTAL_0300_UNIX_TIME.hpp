	if((__DATE__[0] == 'M') && (__DATE__[1] == 'a') && (__DATE__[2] == 'r')){id.month= 3;}
	if((__DATE__[0] == 'A') && (__DATE__[1] == 'p'))						  {id.month= 4;}
	if((__DATE__[0] == 'M') && (__DATE__[1] == 'a') && (__DATE__[2] == 'y')){id.month= 5;}
	if((__DATE__[0] == 'J') && (__DATE__[1] == 'u') && (__DATE__[2] == 'n')){id.month= 6;}
