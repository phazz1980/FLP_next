//						10. Расчет параметров  текущего дня недели
//						       параметрам день, месяц и год
//=================================================================================================
  uint8_t unixSetWeekDay(uint8_t day, uint8_t month, uint16_t year){
   (void)day; (void)month; (void)year; 
    uint16_t w0;
//-------------------------------------------------------------------------------------------------
	if(year >= 2000) {year -= 2000;}
	w0 = day;
	for(uint8_t i = 1; i < month; ++i){w0 +=unixGetDim(i - 1);}
	if (month > 2 && year % 4 == 0)          {++w0;}
	return (w0 + 365 * year + (year+ 3) / 4 + 4) % 7 + 1;	
//--------------------------------------------------------------------------------------------------
  };

