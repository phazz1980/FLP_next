//						16. Преобразование timeUNIX во время и дату.
//=================================================================================================
void   unixGetFromUnixTime(RT_HW_STRUCT_UNIX_ID &id, uint32_t vTimeUNIX, uint8_t vZone){
      (void)id;	(void)vTimeUNIX;
//-------------------------------------------------------------------------------------------------
  uint8_t  b0;
  uint16_t w0,w1,w2,w3,w4; 
  uint32_t d0,d1;
//-------------------------------------------------------------------------------------------------
  id.zone=vZone;							//--Сохранение часового пояса;
  id.timeUNIX=vTimeUNIX;					//--Сохранение timeUNIX (кол-во секунд с 01.01.1970 по Гринвичу);								
  d0=id.timeUNIX + (3600*id.zone); //--Сохранение timeZone (кол-во секунд с 01.01.1970 по указанному часовому поясу);
  id.seconds = d0 % 60UL; d0 /= 60UL;		//--Сохранение секунд;
  id.minutes = d0 % 60UL; d0 /= 60UL;		//--Сохранение минут;
  id.hours   = d0 % 24UL; d0 /= 24UL;		//--Сохранение часов;	  
  id.weekDay =(d0 + 4) % 7; 				//--Сохранение дня недели; 
  if (!id.weekDay) {id.weekDay = 7;} 		
  d1         = d0 + 719468;
  b0         = d1 / 146097ul;
  w0         = d1 - b0 * 146097ul;
  w1         =(w0 - w0 / 1460 + w0 / 36524 - w0 / 146096) / 365;
  w2         = w1 + b0 * 400;
  w3         = w0 -(w1 * 365 + w1 / 4 - w1 / 100);
  w4         =(w3 * 5 + 2) / 153;			
  id.day     = w3 - (w4 * 153 + 2) / 5 + 1;	//--Сохранение дня;
  id.month   = w4 + (w4 < 10 ? 3 : -9);		//--Сохранение месяца;
  w2        +=(id.month <= 2);
  id.year    = w2%100;  					//--Сохранение года;
};

