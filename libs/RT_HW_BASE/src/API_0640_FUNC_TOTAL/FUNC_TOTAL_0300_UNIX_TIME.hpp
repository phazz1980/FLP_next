  uint8_t unixGetDim(uint8_t i){return (i < 7) ? ((i == 1) ? 28 : ((i & 1) ? 30 : 31)) : ((i & 1) ? 31 : 30);};

//=================================================================================================
//						4. Фиксация timeUNIX (кол-во секунд с 01.01.1970 по Гринвичу) 
//						   Фиксация timeZone (кол-во секунд с 01.01.1970 по указанному часовому поясу)
//                         из параметров RT_HW_STRUCT_UNIX_ID &id
// Примечание: обычно используется для начальной инициализация timeUnix,timeZone
//=================================================================================================
  void unixSetTimeUNIX(RT_HW_STRUCT_UNIX_ID &id){
	(void)id;
     uint8_t  b0;
     uint16_t w0,w1,w2; 
//-------------------------------------------------------------------------------------------------
	if(abs(id.zone)<=12){w2=id.zone*60;}	//--Пересчет   параметра сдвига часового пояса в мин; 
	else                {w2=id.zone;}		//--Сохранение параметра сдвига часового пояса в мин; 
	id.year4=2000+id.year;				//--Получение  года в формате xxxx;
//-------------------------------------------------------------------------------------------------
	b0 =(id.month >= 3) ? 1 : 0; 
	w0 = id.year4 + b0 - 1970;	 
	w1 =0;
	for(uint8_t i=0; i<(id.month-1); i++){w1 += unixGetDim(i);}
//-------------------------------------------------------------------------------------------------
//				Фиксация timeUNIX (кол-во секунд с 01.01.1970 по Гринвичу)
//-------------------------------------------------------------------------------------------------
	id.timeUNIX=(((id.day - 1 + w1 + ((w0 + 1) / 4) - ((w0 + 69) / 100) + ((w0 + 369) / 100 / 4) 
				+ 365 * (w0-b0)) * 24ul + id.hours) * 60ul + id.minutes - w2) * 60ul + id.seconds;
//-------------------------------------------------------------------------------------------------
//				Фиксация timeZone (кол-во секунд с 01.01.1970 указанному по часовому поясу)
//-------------------------------------------------------------------------------------------------
	id.fresh=1;
//-------------------------------------------------------------------------------------------------
};
//-------------------------------------------------------------------------------------------------
	void unixSetTimeUNIX(){unixSetTimeUNIX(unixID);}

//=================================================================================================
//						5. Фиксация параметров текущего времени (часы,минуты,секунды)
//							           для указанного часового пояса
//=================================================================================================
  void unixSetTime(RT_HW_STRUCT_UNIX_ID &id){
    uint8_t  b0;
    uint32_t d0;
//-------------------------------------------------------------------------------------------------
	d0=id.timeUNIX + (3600*id.zone);	    	//--UNIX время с учетом часового пояса;
//-------------------------------------------------------------------------------------------------
	id.seconds = d0 % 60UL; d0 /= 60UL;		//--Сохранение секунд;
	id.minutes = d0 % 60UL; d0 /= 60UL;		//--Сохранение минут;
	b0         = d0 % 24UL; d0 /= 24UL;		//--Часы;
	id.hours=b0;								//--Сохранение часов;
  };
//-------------------------------------------------------------------------------------------------
	void unixSetTime(){unixSetTime(unixID);}

//=================================================================================================
//						6. Фиксация параметров текущей даты (день недели,день,месяц,год xx, год хххх)
//							           для указанного часового пояса 
//=================================================================================================
	void unixSetDate(RT_HW_STRUCT_UNIX_ID &id){
	  (void)id;
	  uint8_t  b0;
	  uint16_t w0,w1,w2,w3,w4; 
	  uint32_t d0,d1;
//-------------------------------------------------------------------------------------------------
	d0        =(id.timeUNIX+ 3600*id.zone)/86400;	   //--UNIX время с учетом часового пояса;
	id.weekDay=(d0 + 4) % 7;  if (!id.weekDay) {id.weekDay = 7;}
	d1        = d0 + 719468;
	b0        = d1 / 146097ul;
	w0        = d1 - b0 * 146097ul;
	w1        =(w0 - w0 / 1460 + w0 / 36524 - w0 / 146096) / 365;
	w2        = w1 + b0 * 400;
	w3        = w0 - (w1 * 365  + w1 / 4     - w1 / 100);
	w4        =(w3 * 5 + 2) / 153;
	id.day    = w3 - (w4 * 153 + 2) / 5 + 1;
	id.month  = w4 + (w4 < 10 ? 3 : -9);
	w2       +=(id.month <= 2);
	id.year4  = w2;
	id.year   =id.year4%100;
	};
//---------------------------------------------------------------------------------------------------
  void unixSetDate(){unixSetDate(unixID);}

