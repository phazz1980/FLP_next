  uint8_t  setFistFreeDevice(uint16_t &reg, uint8_t maxNum=16){				
  if((maxNum>16) || (maxNum==0)) {return 0;} 
  for(uint8_t i=1; i<=maxNum; i++){if(!bitRead(reg,(i-1))) {bitSet(reg,(i-1)); return i;}} return 0;};	
