//=================================================================================================
//									6.1. Функция гистерезиса 
// Меняет значение var на cur при его отклонение на delta 
//=================================================================================================	
uint16_t makeDelta(uint16_t &var, uint16_t cur, uint8_t delta){			
  if(cur>var){if((cur-var)>delta){var=cur;}} 
  if(cur<var){if((var-cur)>delta){var=cur;}} return var;
}
//=================================================================================================
//									6.2. Извлечение цифры из числа
// Возвращает цифру(как символ) из vaк начиная со старшей позиции;
// mode B,b,H,h,D,I,0,1,2,3,T; upper =0 верхний регистр, =1 нижний регистр;
//=================================================================================================
uint8_t	getCharVar(uint32_t var,uint8_t upper,char mode,uint8_t len,uint8_t n){
  uint32_t  bf32=0;
  if((mode=='B') || (mode=='b')) {bf32=(var>>(len-n))&1;}
  if((mode=='H') || (mode=='h')) {bf32=(var>>(len-n)*4)&0xf;}
  if((mode=='D') || (mode=='I') ||(mode=='U')|| (mode=='0') ||(mode=='1') ||(mode=='2') || (mode=='3') || (mode=='T')) 
                                          {n=len-n+1; while(n!=0) {bf32=var; var/=10; bf32=bf32-(var*10); n--;};}
  if(bf32<=9) {bf32=bf32 +'0';} else {bf32=bf32-10+(upper ? 'A' : 'a') ;}
  return (uint8_t)bf32;
}; 
