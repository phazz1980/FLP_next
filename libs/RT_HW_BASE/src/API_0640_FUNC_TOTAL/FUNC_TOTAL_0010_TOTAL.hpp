//							1.1.Получение максимального значения для разрядности depth
//=================================================================================================	
uint16_t maxBitDepth(uint8_t depth){
	if(depth>=16) {return 0xFFFF;} 
	if(depth==0)  {return 0;}  
	return ((1<<depth)-1);
}; 
//=================================================================================================
