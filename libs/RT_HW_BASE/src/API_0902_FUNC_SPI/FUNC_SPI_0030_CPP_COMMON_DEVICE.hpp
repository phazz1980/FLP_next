//									4.10. Отправка байт tx, возвращает принятый байт;
//=================================================================================================
  uint8_t		RT_HW_BASE::	spiTransferVar(RT_HW_STRUCT_SPI_DEV &id, uint8_t tx){
	uint8_t bf; (void)bf; (void)id; (void)tx;
	id.link=0; 								//--Сброс флага успешной операции;
	if(id.status!=1){id.link=1; return 0;}	//--Выход, если устройство не настроено;
	if(!spiSetBusy(id.bus))    {return 0;};	//--Ожидание освобождение шины и захват шины;   
//-------------------------------------------------------------------------------------------------
	spiBeginTransaction(id);				//--Начало транзакции;
	spiBeginCS(id);							//--Установка CS в LOW;
	bf=spiTransfer(tx,id.bus);	  			//--Обмен байтами;
	spiEndCS(id);							//--Установка CS в HIGH;
	spiEndTransaction(id);					//--Окончание транзакции;
//-------------------------------------------------------------------------------------------------
	spiClearBusy(id.bus);					//--Освобождение шины;
	id.link=1;								//--Установка флага успешной операции;
    return bf;								//--
  };

