  void		RT_HW_BASE::	spiBeginCS(RT_HW_STRUCT_SPI_DEV &id){
		if(id.t1){delayMicroseconds(id.t1);} 
		pinDigitalWrite(id.ddCS,id.cs,0);
  };
//=================================================================================================
//									4.4. Установка пина СS в HIGH
//=================================================================================================	  
  void		RT_HW_BASE::	spiEndCS(RT_HW_STRUCT_SPI_DEV &id){
		if(id.t2){delayMicroseconds(id.t2);} 
		pinDigitalWrite(id.ddCS,id.cs,1);	
		if(id.t3){delayMicroseconds(id.t3);}
  };	
//=================================================================================================
//									4.5. Настройка устройства
//				Обрабатываются конфликты доступа к шине при одновременном доступе
//									(RTOS,многопроцессорность и т.п.)
//=================================================================================================
  void		RT_HW_BASE::	spiInitDevice(RT_HW_STRUCT_SPI_DEV &id){
	id.link=0;											 //--Очистка параметра;
	if(id.custom==0){id.codeErr=150;id.link=1; 	return;} //--Выход по ошибке =50, если параметры устройство не настроено;
	if(id.status==1){id.codeErr=0;  id.link=1;	return;} //--Проверка настройки устройства;
	if(id.err==1)   {id.codeErr=151;id.link=1; 	return;} //--Выход, если при прежней инициализации была ошибка;
	id.status=id.codeErr=0;											//--Очистка параметров;
//------------------------------------------------------------------------------------------------
	if(!checkPinDOT(id.cs)) {id.codeErr=152; id.link=1; return;}	//--Проверка допустимости номера пина cs;
	spiInitCS(id);													//--Настройка пина CS на вывод;	
//	pinDigitalWrite(id.ddCS,id.cs,1);								//--Настройка пина CS на вывод;		
	if(!checkPinDOT(id.oe)){id.oe=255;} 							//--Проверка допустимости номера пина oe;
	if(id.oe!=255) {digitalWrite(id.oe,1); pinMode(id.oe,OUTPUT); id.stateOe=1;}	//-Настройка пина oe на вывод;	
//-------------------------------------------------------------------------------------------------
	if(!spiCheckBus(id.bus))	{id.codeErr=153; id.err=1; id.link=1; 	return;}	//--Проверка допустимости номера шины SPI;
	if(!spiBegin(id.bus)){												return;};	//--Инициализация шины SPI как Master.
	if( spiGetStatus(id.bus)!=1){id.codeErr=154; id.err=1; id.link=1; 	return;}	//--Проверка настройки шины i2c как Master;
//-------------------------------------------------------------------------------------------------	
	if(id.speed==0){id.speed=RT_HW_SPI_SPEED;}			//--Установка значения скорости шины по умолчанию;
	id.status=spiGetStatus(id.bus);						//--Установка состояния настройки устройства =Master;;
	id.link=1;											//--Успешный выход;	
  };
