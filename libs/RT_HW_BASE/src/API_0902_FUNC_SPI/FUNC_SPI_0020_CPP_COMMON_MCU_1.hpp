//										3.17. Настройка пина СS на вывод
//=================================================================================================  
  void		RT_HW_BASE:: 	spiInitCS (uint8_t cs){
	   digitalWrite(cs, HIGH); 
	   pinMode (cs,OUTPUT);
  };			//==Настройка пина СS на вывод;
//=================================================================================================
//										3.18. Установка пина СS в LOW
//=================================================================================================
  void		RT_HW_BASE:: 	spiBeginCS(uint8_t cs){
	  digitalWrite(cs, LOW);
  };
//=================================================================================================
//										3.19. Установка пина СS в HIGH
//=================================================================================================
  void		RT_HW_BASE:: 	spiEndCS  (uint8_t cs){
	  digitalWrite(cs, HIGH);
  };
