// 		    							3.5. Инициализация параметров (и пинов) по умолчанию для UART num
//=================================================================================================
  void		RT_HW_BASE:: 	spiInitParam (uint8_t bus){
	(void)bus;
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PERMIT_SPI0)							
		if(bus==0)      {LinkSPI0.sck=RT_HW_SPI0_SCK;  LinkSPI0.miso=RT_HW_SPI0_MISO; LinkSPI0.mosi=RT_HW_SPI0_MOSI; return;}
	#endif
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PERMIT_SPI1)							
		if(bus==1)      {LinkSPI1.sck=RT_HW_SPI1_SCK;  LinkSPI1.miso=RT_HW_SPI1_MISO; LinkSPI1.mosi=RT_HW_SPI1_MOSI; return;}
	#endif
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PERMIT_SPI2)							
		if(bus==2)      {LinkSPI2.sck=RT_HW_SPI2_SCK;  LinkSPI2.miso=RT_HW_SPI2_MISO; LinkSPI2.mosi=RT_HW_SPI2_MOSI; return;}
	#endif
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PERMIT_SPI3)							
		if(bus==3)      {LinkSPI3.sck=RT_HW_SPI3_SCK;  LinkSPI3.miso=RT_HW_SPI3_MISO; LinkSPI3.mosi=RT_HW_SPI3_MOSI; return;}
	#endif
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PERMIT_SPI4)							
		if(bus==4)      {LinkSPI4.sck=RT_HW_SPI4_SCK;  LinkSPI4.miso=RT_HW_SPI4_MISO; LinkSPI4.mosi=RT_HW_SPI4_MOSI; return;}
	#endif 
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PERMIT_SPI5)							
		if(bus==5)      {LinkSPI5.sck=RT_HW_SPI5_SCK;  LinkSPI5.miso=RT_HW_SPI5_MISO; LinkSPI5.mosi=RT_HW_SPI5_MOSI; return;}
	#endif
//-------------------------------------------------------------------------------------------------
	#if defined(RT_HW_PERMIT_SPI6)							
		if(bus==6)      {LinkSPI6.sck=RT_HW_SPI6_SCK;  LinkSPI6.miso=RT_HW_SPI6_MISO; LinkSPI6.mosi=RT_HW_SPI6_MOSI; return;}
	#endif
//-------------------------------------------------------------------------------------------------
  }; 
//=================================================================================================
// 		    							3.6. Инициализация параметров (и пинов) по умолчанию для всех UART
//=================================================================================================
  void 		RT_HW_BASE::	spiInitParamAll(){
		for(uint8_t i=0; i<=6; i++){spiInitParam(i); }	//--Установка и настройка пинов SPI по умолчанию;
  };
