  void  pinAnalogRead(RT_HW_PIN_ADC_ID &id){
	(void)id; 
  #if defined RT_HW_PERMIT_PIN_ADC
//-------------------------------------------------------------------------------------------------
//									27.0. Настройка пина (ADC)
//-------------------------------------------------------------------------------------------------
	if(id.dir==0){
		if(!checkPinADC(id.pin)){id.dir=50; return;}				//--Проверка допустимости пина;	
		analogReadResolution(getDepthADC());		
		//pinMode(id.pin, INPUT);									//--Настройка пина для других MCU;;
		id.dir=1;
	}
//-------------------------------------------------------------------------------------------------
//									27.1. Чтение пина (ADC)
//-------------------------------------------------------------------------------------------------
	if(id.dir==1){;
		id.vPin=analogRead(id.pin);
//-------------------------------------------------------------------------------------------------
//									27.1.1. Фильтр дрейфа показаний и дрейфа нуля
//-------------------------------------------------------------------------------------------------
        uint16_t vMax=maxBitDepthADC();		
	if(id.vDev>id.vPin){if((id.vDev-id.vPin)>RT_HW_ADC_DRIFT){id.vDev=id.vPin;}}
	if(id.vDev<id.vPin){if((id.vPin-id.vDev)>RT_HW_ADC_DRIFT){id.vDev=id.vPin;}}
		if(id.vDev>vMax)   {id.vDev=vMax;}
		if(id.vDev<RT_HW_ADC_NULL){id.vDev=0;}
//-------------------------------------------------------------------------------------------------
//									27.1.2. Нормализация значения vDev
//-------------------------------------------------------------------------------------------------
		id.vNorm=normADC(id.vDev);
	}
//-------------------------------------------------------------------------------------------------
  #endif
//------------------------------------------------------------------------------------------------- 
  };	//--END pinADC();
