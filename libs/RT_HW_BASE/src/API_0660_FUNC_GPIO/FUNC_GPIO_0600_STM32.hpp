//									29.  DAC::  Аналоговый вывод
//=================================================================================================
  void 		pinWriteDAC(RT_HW_PIN_DAC_ID &id, uint16_t var){  
	(void)id; (void)var;	
 #if defined(RT_HW_PERMIT_PIN_DAC) 	
//-------------------------------------------------------------------------------------------------
//									21.0. Настройка пина
//-------------------------------------------------------------------------------------------------
	if(id.dir==0){
		if(!checkPinDAC(id.pin)){id.dir=50; return;}//--Проверка допустимости пина; 
//-------------------------------------------------------------------------------------------------
//									21.0.1. STM32F1V
//------------------------------------------------------------------------------------------------- 
	#if defined(RT_HW_CORE_STM32F1V)	
		if(id.pin==PA4){RCC->APB1ENR |= RCC_APB1ENR_DACEN;  DAC->CR |= DAC_CR_EN1;}          //вкл. тактирование ЦАП, вкл. ЦАП 1; 
		if(id.pin==PA5){RCC->APB1ENR |= RCC_APB1ENR_DACEN;  DAC->CR |= DAC_CR_EN2;}          //вкл. тактирование ЦАП, вкл. ЦАП 1;    
	#endif
//-------------------------------------------------------------------------------------------------
//									21.0.2. STM32F407V
//-------------------------------------------------------------------------------------------------  
	#if defined(RT_HW_CORE_STM32F4V)
		analogWriteResolution(getDepthDAC());
	#endif
//-------------------------------------------------------------------------------------------------  
		id.dir=1;
	} 				   
//-------------------------------------------------------------------------------------------------
//									21.1. Настройка пина
//-------------------------------------------------------------------------------------------------
	if(id.dir==1){			
//-------------------------------------------------------------------------------------------------
//									21.1.1. STM32F1V
//------------------------------------------------------------------------------------------------- 
	#if defined(RT_HW_CORE_STM32F1V) 
		id.cash=normDAC(var);
		if(id.pin==PA4){DAC->DHR12R1 = id.cash; return;}       // загрузка данных в ЦАП1
		if(id.pin==PA5){DAC->DHR12R2 = id.cash; return;}       // загрузка данных в ЦАП2
	#endif
//-------------------------------------------------------------------------------------------------
//									21.1.2. STM32F4V
//------------------------------------------------------------------------------------------------- 
	#if defined(RT_HW_CORE_STM32F4V) 		
		id.cash=normDAC(var);		
		analogWrite(id.pin,id.cash);            return;
	#endif	
//-------------------------------------------------------------------------------------------------
	}  //--END if (id.dir==1)
//-------------------------------------------------------------------------------------------------
  #endif
//-------------------------------------------------------------------------------------------------
  };	//--END pinDAC();	
