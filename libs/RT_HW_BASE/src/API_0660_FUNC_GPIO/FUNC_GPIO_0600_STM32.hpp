//									24. DIR:: Дискретный ввод (DIN) с защитой от дребезга
// mode:    I->дискретный ввод; 
//          U->дискретный ввод с подтяжкой к +Vcc; 
//		    D->дискретный ввод с подтяжкой к  GND; 
// 	 	    F->дискретный ввод с плавающим входом (STM32) (floating entrance);
// Примечание: если указан недопустимый режим(помимо перечисленных) 
//             или режим недопустимый для выбранного MCU инициализируется как ввод без подтяжки (I);
//=================================================================================================
  uint8_t pinDigitalRead(RT_HW_PIN_DIR_ID &id, uint32_t &timeBegin, uint16_t period, uint8_t pin, char mode='I'){ 
	(void)id; (void)timeBegin; (void)period; (void)pin; (void)mode;
//-------------------------------------------------------------------------------------------------
  #if defined(RT_HW_PERMIT_PIN_DIN)
//-------------------------------------------------------------------------------------------------
//									24.0. Настройка пина
//-------------------------------------------------------------------------------------------------
	if(id.dir==0){
		if(!checkPinDIN(pin)){id.dir=50; return 0;}			//--Проверка допустимости пина 
		id.pin=pin;											//--Сохранение номера пина;	
		id.mode=mode;										//--Сохранение режима настройки пина;
		id.baseReg = RT_HW_PIN_TO_BASEREG(id.pin);			//--Номер базового регистра;
		id.bitMask = RT_HW_PIN_TO_BITMASK(id.pin);			//--Номер бита в базовом регистре;		
		if(id.mode=='U') {pinMode(id.pin, INPUT_PULLUP);}	//--Инициализация дискретного ввода с подтяжкой к +Vcc;
		else 			 {pinMode(id.pin, INPUT);}			//--Инициализация дискретного ввода без подтяжки;;
		//-----------------------------------------------------------------------------------------
		if(id.inv){id.cash=!RT_HW_DIRECT_READ(id.baseReg, id.bitMask);}
		else	  {id.cash= RT_HW_DIRECT_READ(id.baseReg, id.bitMask);}
		id.dir=1;
	}
//-------------------------------------------------------------------------------------------------
//									24.1. Чтение пина c защитой от дребезга
//-------------------------------------------------------------------------------------------------
	if(id.dir==1){
		uint8_t var=RT_HW_DIRECT_READ(id.baseReg, id.bitMask);	
        if(id.cash!=var){timeBegin=millis(); id.dir=2;} 
	}
//-------------------------------------------------------------------------------------------------
	if(id.dir==2){
		uint8_t var=RT_HW_DIRECT_READ(id.baseReg, id.bitMask); 
		if((getPastMs(timeBegin)< period) && (id.cash==var)) {id.dir=1;} 
		if( getPastMs(timeBegin)>=period)    {id.cash=var;	  id.dir=1;}
	}
//-------------------------------------------------------------------------------------------------
  #endif		//==RT_HW_pinDigitalRead(дребезг)->#if defined(RT_HW_PERMIT_PIN_DIN)
	return  id.cash;
  };

//=================================================================================================
//									25. DINB: Дискретный ввод с защитой от дребезга
// mode:    I->дискретный ввод; 
//          U->дискретный ввод с подтяжкой к +Vcc; 
//		    D->дискретный ввод с подтяжкой к  GND; 
// 	 	    F->дискретный ввод с плавающим входом (STM32) (floating entrance);
// Примечание: если указан недопустимый режим(помимо перечисленных) 
//             или режим недопустимый для выбранного MCU инициализируется как ввод без подтяжки (I);
//=================================================================================================
  uint8_t 	pinDigitalRead	(RT_HW_PIN_DIB_ID &id){ 
	(void)id; 
//-------------------------------------------------------------------------------------------------
  #if defined(RT_HW_PERMIT_PIN_DIN)
//-------------------------------------------------------------------------------------------------
//									25.0. Настройка пина
//-------------------------------------------------------------------------------------------------
	if(id.dir==0){
		if(!checkPinDIN(id.pin)){id.dir=50; return 0;}		//--Проверка допустимости пина 
		id.baseReg = RT_HW_PIN_TO_BASEREG(id.pin);			//--Номер базового регистра;
		id.bitMask = RT_HW_PIN_TO_BITMASK(id.pin);			//--Номер бита в базовом регистре;		
		if(id.mode=='U') {pinMode(id.pin, INPUT_PULLUP);}	//--Инициализация дискретного ввода с подтяжкой к +Vcc;
		else 			 {pinMode(id.pin, INPUT);}			//--Инициализация дискретного ввода без подтяжки;;
		//-----------------------------------------------------------------------------------------
		if(id.inv){id.cash=!RT_HW_DIRECT_READ(id.baseReg, id.bitMask);}
		else	  {id.cash= RT_HW_DIRECT_READ(id.baseReg, id.bitMask);}
		id.dir=1;
	}
//-------------------------------------------------------------------------------------------------
//									25.1. Предварительное чтение пина c защитой от дребезга
//-------------------------------------------------------------------------------------------------
	if(id.dir==1){
		uint8_t var=RT_HW_DIRECT_READ(id.baseReg, id.bitMask);
		if(id.inv){var=!var;}
        if(id.cash!=var){id.timeBegin=millis(); id.dir=2;} 
	}
//-------------------------------------------------------------------------------------------------
//									25.2. Контрольное чтение пина c защитой от дребезга
//-------------------------------------------------------------------------------------------------
	if(id.dir==2){
		uint8_t var=RT_HW_DIRECT_READ(id.baseReg, id.bitMask);
		if(id.inv){var=!var;}
		if((getPastMs(id.timeBegin)< id.period) && (id.cash==var)) {id.dir=1;} 
		if( getPastMs(id.timeBegin)>=id.period)    {id.cash=var;	id.dir=1;}
	}
//-------------------------------------------------------------------------------------------------
  #endif		//==RT_HW_pinDigitalRead(дребезг)->#if defined(RT_HW_PERMIT_PIN_DIN)
	return id.cash;
  };
