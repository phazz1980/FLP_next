//									20. DIR:: Дискретный вывод
// mode:   'N'-нормальный вывод; 'O'-открытый коллектор.
//================================================================================================O
  void  	pinDigitalWrite	(RT_HW_PIN_DIR_ID &id, 				uint8_t var){
	(void)id; (void)var; 
  #if defined RT_HW_PERMIT_PIN_DOT
//-------------------------------------------------------------------------------------------------
//									20.0. Настройка пина
//-------------------------------------------------------------------------------------------------
	if(id.dir==0){
		if(!checkPinDOT(id.pin)){id.dir=50; return;}			//--Проверка допустимости пина 		
		id.bitMask= RT_HW_PIN_TO_BITMASK(id.pin); 
		id.baseReg= RT_HW_PIN_TO_BASEREG(id.pin);;
    id.dir=1;
  //if(id.inv) 	{digitalWrite(id.pin,0); pinMode(id.pin, OUTPUT); id.dir=2;}		 //--Инициализация инверсного вывода;
  //else 		{digitalWrite(id.pin,1); pinMode(id.pin, OUTPUT); id.dir=1;}		 //--Инициализация прямого    вывода;
	if((!id.inv) && (id.mode!='O')){digitalWrite(id.pin, var); pinMode(id.pin, OUTPUT); 			id.dir=1;} //--Инициализация inv=0, mode!='O';	
	if((!id.inv) && (id.mode=='O')){digitalWrite(id.pin,!var); pinMode(id.pin, OUTPUT_OPEN_DRAIN);  id.dir=2;} //--Инициализация inv=0, mode ='O';
    if(( id.inv) && (id.mode!='O')){digitalWrite(id.pin,!var); pinMode(id.pin, OUTPUT); 			id.dir=1;} //--Инициализация inv=1, mode!='O';	
	if(( id.inv) && (id.mode=='O')){digitalWrite(id.pin, var); pinMode(id.pin, OUTPUT_OPEN_DRAIN);  id.dir=2;} //--Инициализация inv=1, mode ='O';
	if(id.dir==0)	{id.inv=0;      digitalWrite(id.pin, var); pinMode(id.pin, OUTPUT); 			id.dir=1;} //--Если не определен;	
	}
//-------------------------------------------------------------------------------------------------
//									20.1. Запись пина - прямое значение
//-------------------------------------------------------------------------------------------------
	if(id.dir==1){   
    #if !defined(RT_HW_BLOCK_QUICK_PIN)
		id.cash=var;
		if(id.inv)	{digitalWrite(id.pin,!id.cash);}
		else  		{digitalWrite(id.pin, id.cash);}
		//if(id.cash)	{RT_HW_DIRECT_WRITE_HIGH(id.baseReg, id.bitMask);}
		//else  		{RT_HW_DIRECT_WRITE_LOW(id.baseReg,  id.bitMask);}
    #else
		id.cash=var;
		if(id.inv)	{digitalWrite(id.pin,!id.cash);}
		else  		{digitalWrite(id.pin, id.cash);}
    #endif
    return;
	}
//-------------------------------------------------------------------------------------------------
//									20.2. Запись пина обратного значения (для открытого выхода)
//-------------------------------------------------------------------------------------------------
	if(id.dir==2){   
    #if !defined(RT_HW_BLOCK_QUICK_PIN)
		id.cash=var;
		if(id.inv)	{digitalWrite(id.pin, id.cash);}
		else  		{digitalWrite(id.pin,!id.cash);}
    #else
		id.cash=var;
		if(id.inv)	{digitalWrite(id.pin,!id.cash);}
		else  		{digitalWrite(id.pin, id.cash);}
    #endif
    return;
	}	
//-------------------------------------------------------------------------------------------------
  #endif
//-------------------------------------------------------------------------------------------------  
  };	//--END pinDigitalWrite();
