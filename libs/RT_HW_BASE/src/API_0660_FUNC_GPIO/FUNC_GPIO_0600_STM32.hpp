//									22. DIR:: Дискретный ввод
// mode:    I->дискретный ввод; 
//          U->дискретный ввод с подтяжкой к +Vcc; 
//		    D->дискретный ввод с подтяжкой к  GND; 
// Примечание: если указан недопустимый режим(помимо перечисленных) 
//             или режим недопустимый для выбранного MCU инициализируется как ввод без подтяжки;
//=================================================================================================
  uint8_t 	pinDigitalRead	(RT_HW_PIN_DIR_ID &id){ 
	(void)id; 
  #if defined RT_HW_PERMIT_PIN_DIN
//-------------------------------------------------------------------------------------------------
//									22.0. Настройка пина
//-------------------------------------------------------------------------------------------------
	if(id.dir==0){
		if(!checkPinDIN(id.pin)){id.dir=50; return 0;}		//--Проверка допустимости пина 
		id.baseReg = RT_HW_PIN_TO_BASEREG(id.pin);			//--Номер базового регистра;
		id.bitMask = RT_HW_PIN_TO_BITMASK(id.pin);			//--Номер бита в базовом регистре;		
		if(id.mode=='U') {pinMode(id.pin, INPUT_PULLUP);}	//--Инициализация дискретного ввода с подтяжкой к +Vcc;
		else 			 {pinMode(id.pin, INPUT);}			//--Инициализация дискретного ввода без подтяжки;;
		id.dir=1;
	}
//-------------------------------------------------------------------------------------------------
//									22.1. Чтение пина
//-------------------------------------------------------------------------------------------------
	if(id.dir==1){
    #if !defined(RT_HW_BLOCK_QUICK_PIN)
		if(id.inv){return !RT_HW_DIRECT_READ(id.baseReg, id.bitMask);}	//--Быстрое чтение; 
		else      {return  RT_HW_DIRECT_READ(id.baseReg, id.bitMask);}	//--Быстрое чтение; 
    #else
		if(id.inv){return !digitalRead(id.pin);}						//--Чтение функцией Arduino IDE;
		else      {return  digitalRead(id.pin);}
    #endif
	}
//-------------------------------------------------------------------------------------------------
  #endif
//-------------------------------------------------------------------------------------------------
	return 0;
  };	//--END pinDigitalRead();
