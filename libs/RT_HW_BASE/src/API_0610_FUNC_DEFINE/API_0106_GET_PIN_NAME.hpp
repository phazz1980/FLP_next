uint8_t getPinString(String &str, uint8_t pin, char mode='T'){ 
    String ss; uint8_t sz; (void)pin; (void)mode; (void)ss; (void)sz;
	uint8_t d=0;
//-------------------------------------------------------------------------------------------------
//									1. ESP8266
//-------------------------------------------------------------------------------------------------	 
    #if   defined(RT_HW_CORE_ESP8266)
//-------------------------------------------------------------------------------------------------	
		if(mode=='T'){ss=getNamePin(pin); 
		              sz=ss.length(); 
					  if(sz<3){ss=String(' ')+ss;}
					  str=ss;
					  return d;
					 }					  
//-------------------------------------------------------------------------------------------------
		if(mode=='A'){ss=getNamePin(pin); 
		              sz=ss.length();
					  if(sz<3){ss=String(' ')+ss;}
					  str=ss;
					//-----------------------------------------------------------------------------
					  if(pin<254) {ss=String(pin);} else{ss=String('*')+String('*');}	
					  sz=ss.length(); 
					  if(sz<3){ss=String('[')+String(' ')+ss +String(']');}
					  else    {ss=String('[')+            ss +String(']');}
					  str=str+ss;	
					  return d;
					 }
//-------------------------------------------------------------------------------------------------
		if(mode=='D'){if(pin<254) {ss=String(pin);} else{ss=String('*')+String('*');}
					  sz=ss.length(); 
					  if(sz<3){ss=String(' ')+ss;}
					  str=ss;
					  return d;
					 }
//-------------------------------------------------------------------------------------------------
	#endif
//-------------------------------------------------------------------------------------------------
//									2. STM32
//-------------------------------------------------------------------------------------------------		 
    #if defined(RT_HW_CORE_STM32)
//------------------------------------------------------------------------------------------------- 
		if(mode=='T'){str=getNamePin(pin);
		              sz=str.length();
					  if(sz<4){d=1;}
					  //if(sz<4){ss=String(' ')+ss;}
					  return d;
					 }					  
//-------------------------------------------------------------------------------------------------
		if(mode=='A'){ss=getNamePin(pin); 
		              sz=ss.length(); 
					  if(sz<4){ss=ss+String(' ');}
					  str=ss;
					//-----------------------------------------------------------------------------
					  if(pin<254) {ss=String(pin);} 
					  //else{ss=String('*')+String('*');}	
					  else{ss=String(F(" ** "));}	
					  sz=ss.length();
					  ss=String('['); 
					  if(sz<2) {ss=ss+String(' ');}
					  if(sz<3) {ss=ss+String(' ');}
					  ss=ss+String(pin)+String(']');
					  str=str+ss;	
					  return d;
					 }
//-------------------------------------------------------------------------------------------------
		if(mode=='D'){if(pin<254) {ss=String(pin);} else{ss=String('*')+String('*');}	
					  sz=ss.length(); 
					  if(sz<2){ss=String(' ')+ss;}
					  if(sz<3){ss=String(' ')+ss;}
					  str=ss;
					  return d;
					 }
//-------------------------------------------------------------------------------------------------
	#endif	
//-------------------------------------------------------------------------------------------------
//									3. MCU КРОМЕ ESP8266, STM32
//-------------------------------------------------------------------------------------------------	
    #if !defined(RT_HW_CORE_ESP8266) && !defined(RT_HW_CORE_STM32)
//-------------------------------------------------------------------------------------------------	 	
					  if(pin<254) {ss=String(pin);} else{ss=String('*')+String('*');}	
					  sz=ss.length(); 
					  if(sz<2){ss=String(' ')+ss;}
					  str=ss;
					  return d;
//-------------------------------------------------------------------------------------------------	
	#endif
//-------------------------------------------------------------------------------------------------
//									4. НЕ ОПОЗНАННЫЙ ПИН
//-------------------------------------------------------------------------------------------------
	return d;	
};

